// getIDECommand returns the command to open the project in the selected IDE
func getIDECommand(ide string) string {
	switch strings.ToLower(ide) {
	case "cursor":
		return "cursor"
	case "claude code", "claudecode":
		return "claude"
	case "antigravity":
		return "antigravity"
	case "windsurf":
		return "windsurf"
	case "cline":
		return "cline"
	case "opencode":
		return "opencode"
	default:
		return "code"
	}
}

// getPrimaryIDE returns the first IDE from the list (if any)
func getPrimaryIDE(ides []string) string {
	if len(ides) == 0 {
		return ""
	}
	return ides[0]
}

// formatIDEList turns the IDE slice into a human-readable string.
func formatIDEList(ides []string) string {
	if len(ides) == 0 {
		return "your preferred IDE"
	}
	if len(ides) == 1 {
		return ides[0]
	}
	return strings.Join(ides, ", ")
}

// generateFooter creates a well-designed footer for generated documentation
// projectName: The name of the project
// agentName: The name of the agent that generated this document (e.g., "Documentation Lead", "Product Manager")
func generateFooter(projectName, agentName string) string {
	currentDate := time.Now().Format("2006-01-02")
	doplanVersion := version.GetVersion()
	if doplanVersion == "dev" {
		doplanVersion = "latest"
	}

	return fmt.Sprintf(`______________

%s Documentation 

Generated by: DoPlan CLI  v%s

Sup-Agent: %s

Date :  %s`, projectName, doplanVersion, agentName, currentDate)
}

