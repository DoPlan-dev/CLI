// DocsGenerator generates documentation files
type DocsGenerator struct{}

// Name returns the name of the generator
func (g *DocsGenerator) Name() string {
	return "Documentation"
}

// Generate creates documentation files
func (g *DocsGenerator) Generate(request *models.ProjectRequest, projectPath string) error {
	// Generate README.md
	if err := generateREADME(projectPath, request); err != nil {
		return fmt.Errorf("failed to generate README.md: %w", err)
	}

	// Generate STANDUP.md
	if err := generateSTANDUP(projectPath, request); err != nil {
		return fmt.Errorf("failed to generate STANDUP.md: %w", err)
	}

	// Generate CHANGELOG.md
	if err := generateCHANGELOG(projectPath, request); err != nil {
		return fmt.Errorf("failed to generate CHANGELOG.md: %w", err)
	}

	// Generate rules README
	if err := generateRulesREADME(projectPath, request); err != nil {
		return fmt.Errorf("failed to generate rules README: %w", err)
	}

	// Scaffold Docs/ hierarchy
	if err := generateDocsHierarchy(projectPath); err != nil {
		return fmt.Errorf("failed to scaffold Docs hierarchy: %w", err)
	}

	return nil
}

