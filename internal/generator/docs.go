func generateDocsHierarchy(projectPath string) error {
	docsRoot := filepath.Join(projectPath, "docs")
	if err := utils.CreateDirectory(docsRoot); err != nil {
		return err
	}

	categories := []struct {
		name string
		desc string
	}{
		{"overview", "Project overview, agent hierarchy, onboarding guides"},
		{"references", "Command cheat sheets, integration notes, examples"},
		{"tutorials", "Guided walkthroughs, training notes, onboarding lessons"},
		{"history", "Changelog, meeting summaries, audit logs"},
		{"ops", "Release plans, security audits, CI/CD documentation"},
		{"research", "Discovery interviews, brainstorms, competitive analysis"},
	}

	for _, cat := range categories {
		dir := filepath.Join(docsRoot, cat.name)
		if err := utils.CreateDirectory(dir); err != nil {
			return err
		}
		gitkeep := filepath.Join(dir, ".gitkeep")
		if err := utils.WriteFile(gitkeep, []byte("")); err != nil {
			return err
		}
	}

	readmeContent := "# Docs Directory\n\n" +
		"DoPlan keeps every long-form artifact inside `docs/` so the repository root stays clean. Use these canonical subfolders:\n\n" +
		"| Directory | Purpose |\n" +
		"| --- | --- |\n" +
		"| `docs/overview/` | Project overview, mission, agent hierarchy |\n" +
		"| `docs/references/` | Command cheat sheets and reusable examples |\n" +
		"| `docs/tutorials/` | Guided walkthroughs and training notes |\n" +
		"| `docs/history/` | Changelog, meeting notes, audit logs |\n" +
		"| `docs/ops/` | Release checklists, security reviews, CI/CD docs |\n" +
		"| `docs/research/` | Brainstorms, interviews, experiment logs |\n\n" +
		"## Rules\n\n" +
		"1. **All docs live under `docs/`.** Keep the repository root clean.\n" +
		"2. **Folder = contract.** When you add a new category, document it here so agents know where to write.\n" +
		"3. **History lives in `docs/history/`.** Capture retrospectives, decision logs, and state snapshots there.\n" +
		"4. **Link, don't duplicate.** Reference existing docs rather than copying content across folders.\n\n" +
		"Need another category? Create it under `docs/` and update this README so future scans stay consistent.\n"

	readmePath := filepath.Join(docsRoot, "README.md")
	return utils.WriteFile(readmePath, []byte(readmeContent))
}

// GenerateDocumentation is a convenience function that creates a DocsGenerator and generates documentation
func GenerateDocumentation(request *models.ProjectRequest, projectPath string) error {
	generator := &DocsGenerator{}
	return generator.Generate(request, projectPath)
}
