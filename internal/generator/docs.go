// getIDECommand returns the command to open the project in the selected IDE
func getIDECommand(ide string) string {
	switch strings.ToLower(ide) {
	case "cursor":
		return "cursor"
	case "claude code", "claudecode":
		return "claude"
	case "antigravity":
		return "antigravity"
	case "windsurf":
		return "windsurf"
	case "cline":
		return "cline"
	case "opencode":
		return "opencode"
	default:
		return "code"
	}
}

